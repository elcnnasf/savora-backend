async function seed() {
  let inserted = 0, skipped = 0, failed = 0;

  // The recipes.title column has no UNIQUE constraint, so upsert({ onConflict: 'title' })
  // is not possible. Instead we fetch existing titles and insert only the missing ones,
  // which keeps this script safe to re-run (idempotent).
  const { data: existing, error: fetchError } = await supabaseAdmin
    .from('recipes')
    .select('title');
  if (fetchError) {
    console.error(`Could not read existing recipes: ${fetchError.message}`);
    return;
  }
  const existingTitles = new Set((existing ?? []).map((r) => r.title));

  for (const recipe of recipes) {
    if (existingTitles.has(recipe.title)) {
      console.log(`SKIP "${recipe.title}" (already exists)`);
      skipped++;
      continue;
    }
    const { error } = await supabaseAdmin.from('recipes').insert(recipe);
    if (error) { console.error(`FAIL "${recipe.title}": ${error.message}`); failed++; }
    else { console.log(`OK   "${recipe.title}"`); inserted++; }
  }
  console.log(`\nDone: ${inserted} inserted, ${skipped} skipped, ${failed} failed.`);
}

